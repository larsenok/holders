import { promises as fs } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const TARGET_DIRS = ['src/components', 'src/pages', 'src/hooks', 'src/providers', 'src/api', 'src/data', 'src/utils', 'src/types'];
const OUTPUT = 'docs/agent-context.md';

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(fullPath)));
    } else {
      files.push(fullPath);
    }
  }

  return files;
}

function byFolder(files, rootPrefix) {
  const map = new Map();

  for (const file of files) {
    const rel = path.relative(ROOT, file).replace(/\\/g, '/');
    const folder = path.dirname(rel);
    if (!folder.startsWith(rootPrefix)) continue;
    if (!map.has(folder)) map.set(folder, []);
    map.get(folder).push(rel);
  }

  return map;
}

function sectionTitle(dir) {
  const clean = dir.replace(/^src\//, '');
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}

async function generate() {
  const lines = [];
  lines.push('# Agent context map');
  lines.push('');
  lines.push('Auto-generated by `npm run agent:context`.');
  lines.push('This file is intentionally compact to speed up agent onboarding.');
  lines.push('');

  for (const target of TARGET_DIRS) {
    const abs = path.join(ROOT, target);
    let files = [];
    try {
      files = (await walk(abs)).filter((f) => /\.(ts|tsx)$/.test(f));
    } catch {
      continue;
    }

    lines.push(`## ${sectionTitle(target)}`);

    if (files.length === 0) {
      lines.push('- No TypeScript files found.');
      lines.push('');
      continue;
    }

    const grouped = byFolder(files, target);
    const folders = [...grouped.keys()].sort();

    lines.push(`- Total files: **${files.length}**`);
    lines.push(`- Folders: **${folders.length}**`);
    lines.push('');

    for (const folder of folders) {
      const folderFiles = grouped.get(folder) ?? [];
      const sample = folderFiles.slice(0, 4).map((f) => `\`${path.basename(f)}\``).join(', ');
      lines.push(`- \`${folder}\` (${folderFiles.length})${sample ? ` → ${sample}` : ''}`);
    }

    lines.push('');
  }

  await fs.writeFile(path.join(ROOT, OUTPUT), `${lines.join('\n')}\n`, 'utf8');
  console.log(`Generated ${OUTPUT}`);
}

generate();
